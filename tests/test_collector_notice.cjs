'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('app/static/app.js','utf8');
const helper=source.slice(source.indexOf('function collectorNotice('),source.indexOf('function renderHome('));
const context=vm.createContext({});vm.runInContext(helper,context);
const now='2026-01-01T12:00:00Z';
const base={server_time:now,collector:{state:'ok'},huawei:{quality:'ok',collected_at:now},recording:{pending_samples:0}};
assert.equal(context.collectorNotice(base),null);
const blocked={...base,collector:{state:'auth_blocked',reason:'login_failed'}};
assert.match(context.collectorNotice(blocked).detail,/intervenção necessária/);
assert.match(context.collectorNotice(blocked).detail,/causa não determinada/);
assert.doesNotMatch(context.collectorNotice(blocked).detail,/senha incorreta/);
const retry=context.collectorNotice({...base,collector:{state:'auth_backoff',next_retry_at:now}});
assert.match(retry.detail,/próxima tentativa/);
assert.match(retry.title,/recuperação automática/);
assert.match(context.collectorNotice({...base,recording:{pending_samples:1}}).title,/pendente/);
assert.match(context.collectorNotice({...base,huawei:{quality:'stale'}}).title,/Sem leitura/);
assert.doesNotMatch(context.collectorNotice({...base,collector:{state:'auth_backoff'}}).detail,/próxima tentativa/);
console.log('collector notice: synthetic state contracts passed');
